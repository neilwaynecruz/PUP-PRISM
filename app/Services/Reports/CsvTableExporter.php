<?php

namespace App\Services\Reports;

use App\Services\Reports\Support\TableReport;
use Symfony\Component\HttpFoundation\ResponseHeaderBag;
use Symfony\Component\HttpFoundation\StreamedResponse;

class CsvTableExporter
{
    public function download(TableReport $report): StreamedResponse
    {
        $filename = sprintf(
            '%s-%s.csv',
            $report->filenameBase,
            $report->generatedAt->format('Y-m-d-His'),
        );

        return response()->streamDownload(function () use ($report): void {
            $handle = fopen('php://output', 'wb');

            if ($handle === false) {
                return;
            }

            fwrite($handle, "\xEF\xBB\xBF");

            fputcsv($handle, [$this->sanitizeCellValue($report->title)]);
            fputcsv($handle, ['Generated at', $report->generatedAt->format('Y-m-d H:i:s T')]);
            fputcsv($handle, ['Generated by', $this->sanitizeCellValue($report->generatedBy)]);

            foreach ($report->filters as $label => $value) {
                fputcsv($handle, [
                    $this->sanitizeCellValue($label),
                    $this->sanitizeCellValue($value),
                ]);
            }

            fputcsv($handle, []);
            fputcsv($handle, array_map([$this, 'sanitizeCellValue'], array_values($report->columns)));

            foreach ($report->rows as $row) {
                $cells = [];

                foreach (array_keys($report->columns) as $key) {
                    $cells[] = $this->sanitizeCellValue($row[$key] ?? '');
                }

                fputcsv($handle, $cells);
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => (new ResponseHeaderBag)->makeDisposition(
                ResponseHeaderBag::DISPOSITION_ATTACHMENT,
                $filename,
            ),
        ]);
    }

    /**
     * Sanitize untrusted cell values to prevent CSV formula injection.
     *
     * Prepend single quote (') if the value starts with formula characters (=, +, -, @)
     * or control characters, while preserving legitimate numbers, floats, and empty values.
     */
    public function sanitizeCellValue(mixed $value): string
    {
        if ($value === null) {
            return '';
        }

        if (is_int($value) || is_float($value)) {
            return (string) $value;
        }

        $str = (string) $value;

        // Preserve pure numbers (including negative numbers and floats, e.g. "-10", "-42.50", "+5")
        if (is_numeric($str) && preg_match('/^[+-]?\d+(\.\d+)?$/', trim($str))) {
            return $str;
        }

        // Check for leading formula trigger characters (=, +, -, @)
        // Also account for leading whitespace/tabs/control characters hiding a formula trigger
        $trimmed = ltrim($str, " \t\n\r\0\x0B");

        if ($trimmed !== '' && in_array($trimmed[0], ['=', '+', '-', '@'], true)) {
            return "'".$str;
        }

        // Check for leading control characters (tab, newline, carriage return)
        if ($str !== '' && in_array($str[0], ["\t", "\r", "\n"], true)) {
            return "'".$str;
        }

        return $str;
    }
}
